// Regenerates lib/src/icons/cs_icons.g.dart from the Cloudscape SVG icons in
// tool/icons (copied from cloudscape-design/components src/icon/icons,
// Apache-2.0).
//
//   dart run tool/generate_icons.dart
//
// Cloudscape icons are 16x16 outlines drawn with `stroke: currentColor` and a
// stroke width that depends on the rendered size. They are kept as vector
// paths (not a font) so CsIcon can apply the same per-size stroke widths.
// Circles, ellipses and rects become path data; nested viewports and the
// calendar corner clip become clip rects; `pathLength=1` dash offsets (the
// resting state of Cloudscape's hover motion) become a visible fraction.
import 'dart:io';

void main() {
  final files = Directory('tool/icons').listSync().whereType<File>().where((f) => f.path.endsWith('.svg')).toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/generate_icons.dart from the Cloudscape SVG icons. Do not edit.')
    ..writeln('// Source: github.com/cloudscape-design/components src/icon/icons, Apache-2.0.')
    ..writeln()
    ..writeln("import 'cs_icon_data.dart';")
    ..writeln()
    ..writeln('/// The ${files.length} built-in Cloudscape icons. Names follow Cloudscape\'s')
    ..writeln('/// `iconName` in camelCase: `"status-positive"` is [CsIcons.statusPositive].')
    ..writeln('abstract final class CsIcons {');
  final names = <String>[];
  for (final f in files) {
    final kebab = f.uri.pathSegments.last.replaceAll('.svg', '');
    final name = _camel(kebab);
    names.add(name);
    final parts = _parts(f.readAsStringSync());
    b
      ..writeln('  /// `$kebab`.')
      ..writeln("  static const CsIconData $name = CsIconData('$kebab', [");
    for (final p in parts) {
      b.writeln('    $p,');
    }
    b.writeln(_mirrored.contains(kebab) ? '  ], matchTextDirection: true);' : '  ]);');
  }
  b
    ..writeln()
    ..writeln('  /// Every built-in icon, in name order.')
    ..writeln('  static const List<CsIconData> all = [${names.join(', ')}];')
    ..writeln()
    ..writeln('  /// Looks an icon up by its Cloudscape name (`"status-positive"`).')
    ..writeln('  static CsIconData? byName(String name) {')
    ..writeln('    for (final icon in all) {')
    ..writeln('      if (icon.name == name) return icon;')
    ..writeln('    }')
    ..writeln('    return null;')
    ..writeln('  }')
    ..writeln('}');
  File('lib/src/icons/cs_icons.g.dart')
    ..createSync(recursive: true)
    ..writeAsStringSync(b.toString());
  stdout.writeln('Generated ${files.length} icons');
}

// Icons Cloudscape flips in right-to-left layouts (src/icon/styles.scss).
const _mirrored = {
  'angle-left-double', 'angle-left', 'angle-right-double', 'angle-right', 'arrow-left', 'arrow-right',
  'caret-left-filled', 'caret-right-filled', 'audio-full', 'audio-half', 'audio-off', 'external', 'redo',
  'resize-area', 'send', 'shrink', 'undo', 'view-vertical', 'view-vertical-start',
};

String _camel(String kebab) {
  final parts = kebab.split('-');
  return parts.first + parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
}

final _element = RegExp(r'<(path|circle|rect|ellipse|svg)\b([^>]*?)(/?)>|</svg>');
final _attr = RegExp(r'([\w:-]+)="([^"]*)"');

List<String> _parts(String svg) {
  final out = <String>[];
  // Nested <svg> elements with overflow hidden clip their children.
  final clipStack = <List<double>?>[];
  var depth = 0;
  for (final m in _element.allMatches(svg)) {
    if (m[0] == '</svg>') {
      depth--;
      if (clipStack.isNotEmpty) clipStack.removeLast();
      continue;
    }
    final tag = m[1]!;
    final attrs = {for (final a in _attr.allMatches(m[2]!)) a[1]!: a[2]!};
    if (tag == 'svg') {
      depth++;
      if (depth > 1) {
        final x = double.parse(attrs['x'] ?? '0');
        final y = double.parse(attrs['y'] ?? '0');
        clipStack.add([x, y, x + double.parse(attrs['width']!), y + double.parse(attrs['height']!)]);
      } else {
        clipStack.add(null);
      }
      continue;
    }
    String d;
    double n(String k) => double.parse(attrs[k] ?? '0');
    switch (tag) {
      case 'path':
        d = attrs['d']!;
      case 'circle':
        final cx = n('cx'), cy = n('cy'), r = n('r');
        d = 'M${_f(cx - r)} ${_f(cy)}A${_f(r)} ${_f(r)} 0 1 0 ${_f(cx + r)} ${_f(cy)}'
            'A${_f(r)} ${_f(r)} 0 1 0 ${_f(cx - r)} ${_f(cy)}Z';
      case 'ellipse':
        final cx = n('cx'), cy = n('cy'), rx = n('rx'), ry = n('ry');
        d = 'M${_f(cx - rx)} ${_f(cy)}A${_f(rx)} ${_f(ry)} 0 1 0 ${_f(cx + rx)} ${_f(cy)}'
            'A${_f(rx)} ${_f(ry)} 0 1 0 ${_f(cx - rx)} ${_f(cy)}Z';
      case 'rect':
        final x = n('x'), y = n('y'), w = n('width'), h = n('height');
        final rx = attrs.containsKey('rx') ? n('rx') : (attrs.containsKey('ry') ? n('ry') : 0.0);
        if (rx == 0) {
          d = 'M${_f(x)} ${_f(y)}H${_f(x + w)}V${_f(y + h)}H${_f(x)}Z';
        } else {
          d =
              'M${_f(x + rx)} ${_f(y)}H${_f(x + w - rx)}A${_f(rx)} ${_f(rx)} 0 0 1 ${_f(x + w)} ${_f(y + rx)}'
              'V${_f(y + h - rx)}A${_f(rx)} ${_f(rx)} 0 0 1 ${_f(x + w - rx)} ${_f(y + h)}'
              'H${_f(x + rx)}A${_f(rx)} ${_f(rx)} 0 0 1 ${_f(x)} ${_f(y + h - rx)}'
              'V${_f(y + rx)}A${_f(rx)} ${_f(rx)} 0 0 1 ${_f(x + rx)} ${_f(y)}Z';
        }
      default:
        continue;
    }
    final classes = (attrs['class'] ?? '').split(' ');
    final filled = classes.contains('filled');
    final stroked = !classes.contains('no-stroke');
    final roundJoin = classes.contains('stroke-linejoin-round');
    final cap = classes.contains('stroke-linecap-round')
        ? 'round'
        : classes.contains('stroke-linecap-square')
        ? 'square'
        : null;
    double? visible;
    if (attrs['pathLength'] == '1' && attrs.containsKey('stroke-dasharray')) {
      visible = 1 - double.parse(attrs['stroke-dashoffset'] ?? '0');
    }
    List<double>? clip = clipStack.isNotEmpty ? clipStack.last : null;
    final clipPath = attrs['clip-path'];
    if (clipPath != null) {
      // inset(top right bottom left) of the element's box, in percent.
      final m = RegExp(r'inset\(([^)]*)\)').firstMatch(clipPath)!;
      final p = m[1]!.split(RegExp(r'\s+')).map((s) => double.parse(s.replaceAll('%', '')) / 100).toList();
      final x = n('x'), y = n('y'), w = n('width'), h = n('height');
      // Extend outward edges by the stroke so the clipped corner keeps its full line.
      clip = [x + w * p[3], y + h * p[0], x + w - w * p[1] + 2, y + h - h * p[2] + 2];
    }
    final args = [
      "'${d.replaceAll(RegExp(r'\s+'), ' ').trim()}'",
      if (filled) 'filled: true',
      if (!stroked) 'stroked: false',
      if (roundJoin) 'roundJoin: true',
      if (cap != null) 'cap: CsIconCap.$cap',
      if (visible != null && visible < 1) 'visible: ${_f(visible)}',
      if (clip != null) 'clip: [${clip.map(_f).join(', ')}]',
    ];
    out.add('CsIconPart(${args.join(', ')})');
  }
  return out;
}

String _f(double v) {
  final s = v.toStringAsFixed(4).replaceFirst(RegExp(r'\.?0+$'), '');
  return s == '-0' ? '0' : s;
}
